import '@fontsource/barlow/latin-400.css';
import '@fontsource/barlow/latin-500.css';
import '@fontsource/barlow/latin-700.css';
import '@fontsource/barlow-condensed/latin-400.css';
import '@fontsource/barlow-condensed/latin-600.css';
import './styles/tokens.css';
import './styles/app.css';
import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { App } from './App';
import { refreshMe } from './lib/session';
import { syncEngine } from './lib/sync';

async function boot() {
  // Dev-only API shim (VITE_MOCK_API=1). Statically false in normal builds, so it is tree-shaken out.
  if (import.meta.env.VITE_MOCK_API === '1') {
    const { installMockApi } = await import('./dev/mockApi');
    installMockApi();
  }

  // Service worker (generated by vite-plugin-pwa, precaches the app shell + fonts) so the app opens offline.
  // autoUpdate: the new worker skips waiting and claims clients; the next navigation uses the new shell.
  if ('serviceWorker' in navigator && import.meta.env.PROD) {
    const register = () => void navigator.serviceWorker.register('/sw.js', { scope: '/' }).catch(() => {});
    if (document.readyState === 'complete') register();
    else window.addEventListener('load', register, { once: true });
  }

  // Ask the browser not to evict our IndexedDB (unsynced inspections) under storage pressure.
  void navigator.storage?.persist?.().catch(() => {});

  if (navigator.onLine) void refreshMe();
  syncEngine.start();

  createRoot(document.getElementById('root')!).render(
    <StrictMode>
      <App />
    </StrictMode>,
  );
}

void boot();
